// Writes src/components/phosphor.ts from @phosphor-icons/core (a dev
// dependency, pinned in package.json). To add an icon, add its name to ICONS
// and run `npm run build:icons`.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const ICONS = [
  'arrow-square-out', 'arrow-left', 'arrow-right', 'download-simple',
  'envelope-simple', 'rss', 'calendar-blank', 'clock', 'music-notes', 'rocket',
  'pencil-simple', 'user', 'images', 'cloud', 'house', 'list', 'x', 'check',
  'info', 'warning', 'github-logo', 'link-simple', 'play', 'pause', 'article',
  'identification-card', 'book-open-text',
];
const WEIGHTS = ['light', 'regular', 'bold'];

const pkg = fileURLToPath(new URL('../node_modules/@phosphor-icons/core/', import.meta.url));
const { version } = JSON.parse(readFileSync(join(pkg, 'package.json'), 'utf8'));
const assets = join(pkg, 'assets');

const inner = (name, weight) => {
  const file = weight === 'regular' ? `${name}.svg` : `${name}-${weight}.svg`;
  const svg = readFileSync(join(assets, weight, file), 'utf8');
  return svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
};

let out = `// Phosphor Icons ${version} (@phosphor-icons/core), MIT. Inner SVG markup on a
// 256 viewBox, copied as shipped. Generated by scripts/build-icons.mjs; do not edit.
export const phosphor = {
`;
for (const name of ICONS) {
  out += `  '${name}': {\n`;
  for (const weight of WEIGHTS) out += `    ${weight}: '${inner(name, weight)}',\n`;
  out += `  },\n`;
}
out += `} as const;\n`;

writeFileSync(new URL('../src/components/phosphor.ts', import.meta.url), out);
console.log(`phosphor.ts: ${ICONS.length} icons, ${WEIGHTS.length} weights`);
